const CATALOGS: Record<Locale, Record<ChatKey, string>> = { en, es };

export function chatText(locale: Locale): ChatText {
  const catalog = CATALOGS[locale];
  return (key, params = {}) => {
    const name = pluralKey(catalog, en, locale, key, params) as ChatKey;
    return fill(catalog[name] ?? en[name], params);
  };
}
