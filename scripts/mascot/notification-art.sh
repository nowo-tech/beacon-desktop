#!/usr/bin/env bash
# Builds the pictures of the native friendly-message notifications from the imported poses.
#
# Usage: scripts/mascot/notification-art.sh
#
# For every pose listed in src/ui/pose-art.json, public/mascot/pose-<id>@2x.webp becomes
# src-tauri/notification-art/pose-<id>.png: a 96 × 96 transparent square with the pose centred (Windows draws it as the
# square app logo of the toast, macOS as the content image, Linux servers through the `image-path` hint; none of them
# reads WebP everywhere). Then src-tauri/src/pose_art.rs lists them with `include_bytes!`, so the binary carries them
# and writes them to the app cache the first time a notification needs one.
#
# Run it after scripts/mascot/import-poses.sh. Needs ImageMagick with WebP support; without it it runs itself in a
# throwaway Debian container (Docker).
set -euo pipefail

SIZE=96

repo="$(cd "$(dirname "$0")/../.." && pwd)"
out="$repo/src-tauri/notification-art"
list="$repo/src-tauri/src/pose_art.rs"

magick_cmd() { if command -v magick >/dev/null 2>&1; then magick "$@"; else convert "$@"; fi; }

if ! { command -v magick >/dev/null 2>&1 || command -v convert >/dev/null 2>&1; } || ! magick_cmd -list format 2>/dev/null | grep -qi '^ *webp'; then
  if [ "${NOTIFICATION_ART_IN_DOCKER:-}" = 1 ]; then
    echo "ImageMagick with WebP missing in the container" >&2
    exit 1
  fi
  exec docker run --rm -v "$repo":/repo -w /repo -e NOTIFICATION_ART_IN_DOCKER=1 -e DEBIAN_FRONTEND=noninteractive \
    "${NOTIFICATION_ART_IMAGE:-debian:stable-slim}" sh -c "
      apt-get update -qq >/dev/null && apt-get install -y -qq --no-install-recommends imagemagick webp >/dev/null &&
      bash scripts/mascot/notification-art.sh; status=\$?; chown -R $(id -u):$(id -g) src-tauri/notification-art src-tauri/src/pose_art.rs; exit \$status"
fi

mkdir -p "$out"
rm -f "$out"/pose-*.png
ids="$(grep -o '"[a-z0-9-]*"' "$repo/src/ui/pose-art.json" | tr -d '"')"
{
  echo '//! Generated by scripts/mascot/notification-art.sh from src/ui/pose-art.json: do not edit.'
  echo '//! Pictures of the native friendly-message notifications (96 × 96 PNG, transparent).'
  echo
  echo 'pub const POSE_ART: &[(&str, &[u8])] = &['
} >"$list"
count=0
for id in $ids; do
  src="$repo/public/mascot/pose-$id@2x.webp"
  [ -f "$src" ] || { echo "missing $src" >&2; exit 1; }
  magick_cmd "$src" -resize "${SIZE}x${SIZE}" -background none -gravity center -extent "${SIZE}x${SIZE}" \
    -strip -define png:compression-level=9 "PNG32:$out/pose-$id.png"
  echo "    (\"$id\", include_bytes!(\"../notification-art/pose-$id.png\"))," >>"$list"
  count=$((count + 1))
done
echo '];' >>"$list"
echo "$count notification picture(s) in src-tauri/notification-art; list in src-tauri/src/pose_art.rs"
